/**
 * Generates Android vector drawables (res/drawable/ms_<name>.xml) from @material-symbols/svg-400 (rounded, Apache-2.0)
 * for the guard app's icons. Add a name to NAMES and run: node scripts/dev/build-android-symbols.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.dirname(require.resolve("@material-symbols/svg-400/package.json"));
const NAMES = ["home", "route", "campaign", "history", "person", "notifications", "notifications_active", "qr_code_scanner", "my_location", "check_circle", "verified_user", "cloud_done", "cloud_off", "login", "arrow_back", "check", "emergency", "support_agent", "thumb_up", "undo", "call", "location_off", "settings", "pause_circle", "error", "schedule", "sync", "dark_mode", "light_mode", "logout", "shield", "report", "directions_run", "chevron_right", "swap_horiz", "chat"];
const out = "android/app/src/main/res/drawable";
for (const n of NAMES) {
  const svg = readFileSync(path.join(root, "rounded", `${n}.svg`), "utf8");
  const vb = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => `        <path android:fillColor="#FFFFFFFF" android:pathData="${m[1]}" />`).join("\n");
  writeFileSync(path.join(out, `ms_${n}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "${n}" (Apache-2.0), generated by scripts/dev/build-android-symbols.mjs. Tint at use. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="${vb[2]}" android:viewportHeight="${vb[3]}">
    <group android:translateX="${-vb[0]}" android:translateY="${-vb[1]}">
${paths}
    </group>
</vector>
`);
}
console.log(`wrote ${NAMES.length} icons`);
